import assert from 'node:assert/strict';
import {toolDetail,mcpForm,mcpDetail,recordDetail} from './static/workforms.js';
import {renderPage} from './static/views.js';
import {assetGraph,explorationGraph} from './static/graphs.js';

const tool={adapter:'mcp',server_name:'analysis',local_name:'读取记录',remote_name:'read',definition:{function:{name:'analysis_read',description:'读取 <record> 记录',parameters:{type:'object',required:['path'],properties:{path:{type:'string',description:'记录路径'},limit:{type:'integer',default:0},recursive:{type:'boolean',default:false},format:{type:'string',enum:['text','json']},options:{type:['object','null']}}}}}};
const detail=toolDetail(tool,'data-index="3"');
for(const text of ['记录路径','必填','可选','integer','object / null','默认值：0','默认值：false','&quot;text&quot; / &quot;json&quot;'])assert.ok(detail.includes(text),text);
assert.match(detail,/data-action="mcp-tools" data-index="3"/);
assert.match(detail,/读取 &lt;record&gt; 记录/);
assert.ok(detail.includes('<details class="request-details"><summary>高级：完整工具定义 / JSON</summary><pre>'));
assert.doesNotMatch(detail,/<details[^>]*open/);
assert.doesNotMatch(toolDetail(tool),/返回服务工具目录/);
assert.match(toolDetail({...tool,definition:{function:{name:'no-schema'}}}),/未提供可展开的参数列表/);
const card=mcpForm({mcp:[{name:'analysis',command:'node'},{name:'disabled',disabled:true,command:'node'}]},[tool]);
assert.match(card,/<article class="mcp-service"[^>]*><button[^>]*data-action="mcp-detail"/);
assert.ok(card.includes('</button><footer>'));
assert.doesNotMatch(card,/data-action="mcp-tools"/);
const config={mcp:[{name:"analysis",command:"node"},{name:"disabled",disabled:true,command:"node"}]};
assert.match(mcpDetail(config,[tool],0),/data-action="mcp-tools" data-index="0"/);
assert.match(mcpDetail(config,[tool],1),/data-action="mcp-tools" data-index="1"[^>]* disabled/);
assert.doesNotMatch(card,/status verified/);
const run={id:'run',goal:'Review',status:'cancelled',usage:{}};
const snap={run,messages:[],assets:[],actions:[],evidence:[],plan:{tasks:[]}};
const state={page:'history',selected:'run',runs:[run],snap,tools:[],historyFilter:''};
const history=renderPage(state);
assert.match(history,/<textarea id="message-content" required disabled/);
assert.match(history,/<select id="message-kind" aria-label="消息类型" disabled/);
assert.match(renderPage({...state,page:'assets'}),/尚未登记资产。展开下方表单/);
const asset={id:'asset',value:'host',kind:'host',coverage:'verified'};
assert.match(assetGraph({...state,graphFilter:'negative',snap:{...snap,assets:[asset]}}),/没有匹配的资产/);
assert.match(explorationGraph(state),/role="group" aria-label="研究目标、探索方向、观测与发现关系图"/);
const task=recordDetail('task-detail',{id:'task',goal:'Check',mode:'reason',dependencies:['first'],priority:0,error:'needs <repair>'},snap);
for(const text of ['依赖任务','first','优先级','分析','needs &lt;repair&gt;'])assert.ok(task.includes(text),text);
console.log('Workspace UX checks passed: readable tool details, separate MCP entry, cancelled composer, record metadata and graph empty states.');
