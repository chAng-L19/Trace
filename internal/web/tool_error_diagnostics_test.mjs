import assert from 'node:assert/strict';
import {callDiagnostics,callStatus,toolCard,toolOutput} from './static/conversation.js';
import {pendingTools,recordDetail} from './static/workforms.js';
import {workerActivity} from './static/workers.js';
import {pauseReason} from './static/ui.js';

const diagnostic={code:'exec_resource_limit',summary:'进程和线程达到单命令上限 64。',next_action:'先核对部分结果；后续建议并发 16。',pids_limit:64,recommended_concurrency:16};
const action={call_id:'exec-1',request_id:'request-1',name:'exec',arguments:'{}',status:'uncertain',started_at:'2026-11-12T02:00:00.000000002Z',finished_at:'2026-11-12T02:00:02.000000002Z',result:{worker_status:'failed',worker_resource_limit:'pids.events:max',error:'ORIGINAL_ERROR',stderr:'ORIGINAL_STDERR',exit_code:1,diagnostic}};
const snap={run:{id:'run-1',status:'paused'},actions:[action],events:[]};
const original=JSON.stringify(snap);
const missingResult=toolCard({...action,result:undefined},snap);
assert.match(missingResult,/执行结果未保存/);
assert.doesNotMatch(missingResult,/等待工具结果/);
assert.equal(callStatus(action),'uncertain');
assert.equal(callStatus({...action,status:'interrupted'}),'interrupted');
for(const exit_code of [1,2])for(const error of ['', 'exit'])assert.equal(callStatus({...action,status:'completed',result:{error,exit_code}}),'failed');
assert.equal(callStatus({...action,status:'completed',result:{exit_code:0}}),'completed');
const output=toolOutput(action.result);
assert.match(output,/诊断：进程和线程达到单命令上限 64/);
assert.match(output,/下一步：先核对部分结果/);
assert.match(output,/ORIGINAL_ERROR/);
assert.match(output,/ORIGINAL_STDERR/);
assert.match(output,/退出码 1/);
assert.doesNotMatch(output,/recommended_concurrency|exec_resource_limit/,'extra fields must not duplicate diagnostic JSON');
for(const html of [toolCard(action,snap),recordDetail('action-detail',action,snap),pendingTools(snap)]){
  assert.match(html,/单命令上限 64/);
  assert.match(html,/后续建议并发 16/);
  assert.match(html,/ORIGINAL_ERROR/);
  assert.doesNotMatch(html,/结果已确认/);
}
const detail=recordDetail('action-detail',action,snap);
assert.match(detail,/status uncertain/);
assert.match(detail,/完整账本字段/);
assert.match(detail,/recommended_concurrency/,'full ledger retains structured diagnostic');
assert.doesNotMatch(detail,/tool-observation-form/,'consumed historical calls do not offer a stale observation form');
const pendingSnap={...snap,messages:[{role:'assistant',request_id:action.request_id,tool_calls:[{id:action.call_id,name:action.name,arguments:action.arguments}]}]};
assert.match(recordDetail('action-detail',action,pendingSnap),/tool-observation-form/,'a pending legacy call retains its optional observation form');
const worker=workerActivity({phase:'paused',cleanup_status:'unknown',calls:[{call_id:'exec-1',status:'uncertain',diagnostic,cleanup_error:'CLEANUP_PENDING'}]});
assert.match(worker,/单命令上限 64/);
assert.match(worker,/下一步：先核对部分结果/);
assert.match(worker,/CLEANUP_PENDING/);
assert.equal(JSON.stringify(snap),original,'rendering never changes the result or ledger');

const legacy={...action,result:{worker_status:'cancelled',error:'signal: killed',exit_code:-1}};
const event={sequence:11,type:'run_paused',created_at:'2026-11-12T02:00:01Z'};
const history={...snap,actions:[legacy],events:[event]};
const legacyBefore=JSON.stringify(history);
assert.equal(callDiagnostics(legacy,history),'','historical FinishedAt includes archival time and cannot prove an execution window');
for(const html of [toolCard(legacy,history),recordDetail('action-detail',legacy,history),pendingTools(history)])assert.doesNotMatch(html,/关联暂停事件|关联取消事件|底层中断原因/);
assert.equal(callStatus(legacy),'uncertain');
assert.equal(callStatus({...legacy,status:'completed'}),'interrupted');
assert.match(toolCard({...legacy,status:'completed'},history),/已中断/);
assert.equal(callDiagnostics(legacy,{events:[{...event,type:'run_cancelled'}]}),'');
assert.equal(callDiagnostics(legacy,{...history,events:[]}),'','current paused run alone is not evidence');
assert.equal(callDiagnostics({...legacy,result:{...legacy.result,worker_status:'failed'}},history),'','failed commands are not attributed to pause');
assert.equal(callDiagnostics({...legacy,result:{...legacy.result,worker_status:undefined}},history),'');
assert.equal(JSON.stringify(history),legacyBefore,'rendering never writes a diagnostic to a historical result');

const control={code:'control_paused',summary:'命令中断，执行窗口内存在暂停事件。',next_action:'核对输出与清理状态。',control_run_id:'run-1',control_event_sequence:11};
const persisted={...legacy,result:{...legacy.result,diagnostic:control}};
assert.match(callDiagnostics(persisted,history),/诊断：命令中断/);
assert.doesNotMatch(callDiagnostics(persisted,history),/历史调用/,'saved diagnostics take precedence over legacy inference');
const scriptError={exit_code:2,error:'exit status 2',stderr:'TypeError: bad format',diagnostic:{code:'script_type_error',summary:'脚本类型错误。',next_action:'核对参数类型，修正出错表达式。'}};
assert.match(toolOutput(scriptError),/脚本类型错误/);
assert.match(toolOutput(scriptError),/核对参数类型/);
assert.match(toolOutput(scriptError),/TypeError: bad format/);
const blocked={...action,status:'completed',name:'task_dispose',result:{error:'DISPOSITION_ERROR',diagnostic:{code:'task_disposition_blocked',summary:'任务处置受阻。',next_action:'核对未完成的清理。',blockers:{worker_id:'worker-1',cleanup_status:'unknown'}}}};
assert.equal(callStatus(blocked),'failed');
assert.match(toolOutput(blocked.result),/任务处置受阻/);
assert.match(toolOutput(blocked.result),/核对未完成的清理/);
assert.doesNotMatch(toolOutput(blocked.result),/worker-1/);
assert.match(recordDetail('action-detail',blocked,snap),/worker-1/,'typed blockers remain available in the full ledger');
assert.match(toolOutput({diagnostic:{summary:'<script>bad</script>',next_action:'<img src=x>'}}),/&lt;script&gt;/);
assert.doesNotMatch(toolOutput({diagnostic:{summary:'<script>bad</script>'}}),/<script>/);
assert.doesNotMatch(pauseReason('tool outcome uncertain; inspect side effects and submit its result manually'),/触发资源上限/,'generic uncertainty does not invent a resource cause');
console.log('Tool diagnostics: preserved uncertainty, raw errors, no legacy control inference, worker summaries and disposition blockers passed');
