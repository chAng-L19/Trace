func TestASCInstalledIntegration(t *testing.T) {
	manifests, status := localtool.Presets(context.Background())
	var asc localtool.Manifest
	for _, m := range manifests {
		if m.Name == "droidasc" {
			asc = m
		}
	}
	if asc.Name == "" {
		t.Skipf("optional droidasc installation absent: %+v", status)
	}
	if asc.GitHubURL != "https://github.com/MG1937/ASC" || asc.LocalPath == "" || asc.Env["PYTHONPATH"] != asc.LocalPath {
		t.Fatalf("source metadata lost: %+v", asc)
	}
	apk := filepath.Join(t.TempDir(), "ASC 中文 & literal.apk")
	// Generated by ASC tests/dex_fixture.py make_dex at d3d75ab (Apache-2.0).
	// Lexample/Test has first()/second() methods referencing the string token.
	dex, err := hex.DecodeString("6465780a30333500963226f50d0a8d2f7737ae22f14eea25db941cbed2e720c8b00100007000000078563412000000000000000034010000060000007000000003000000880000000100000094000000000000000000000002000000a000000001000000b0000000e0000000d0000000d0000000e0000000f4000000f7000000fe000000060100000000000001000000020000000200000002000000000000000000000003000000000000000400000000000000010000000100000000000000ffffffff0000000026010000000000000e4c6578616d706c652f546573743b00124c6a6176612f6c616e672f4f626a6563743b0001560005666972737400067365636f6e640005746f6b656e00000000010000000000000000000000030000001a0005000e0000000200000990020109900200000a0000000000000001000000000000000100000006000000700000000200000003000000880000000300000001000000940000000500000002000000a00000000600000001000000b00000000220000006000000d0000000012000000100000010010000002000000100000026010000001000000100000034010000")
	if err != nil {
		t.Fatal(err)
	}
	f, err := os.Create(apk)
	if err != nil {
		t.Fatal(err)
	}
	archive := zip.NewWriter(f)
	entry, err := archive.Create("classes.dex")
	if err != nil {
		t.Fatal(err)
	}
	if _, err = entry.Write(dex); err != nil {
		t.Fatal(err)
	}
	if err = archive.Close(); err != nil {
		t.Fatal(err)
	}
	if err = f.Close(); err != nil {
		t.Fatal(err)
	}
	args := func(argv ...string) string {
		data, _ := json.Marshal(map[string]any{"argv": argv})
		return string(data)
	}
	selected, _ := json.Marshal(map[string]any{"ids": []string{asc.StableID()}})
	p := &scriptedProvider{responses: []ModelResponse{
		{ToolCalls: []ToolCall{{ID: "search", Name: "tool_search", Arguments: `{"query":"droidasc"}`}}},
		{ToolCalls: []ToolCall{{ID: "select", Name: "tool_select", Arguments: string(selected)}}},
		{ToolCalls: []ToolCall{{ID: "skill", Name: "read_skill", Arguments: `{"name":"asc"}`}}},
		{ToolCalls: []ToolCall{{ID: "classes", Name: asc.StableID(), Arguments: args("listclass", apk)}}},
		{ToolCalls: []ToolCall{{ID: "refs", Name: asc.StableID(), Arguments: args("findrefs", apk, "string", "token")}}},
		{ToolCalls: []ToolCall{{ID: "source", Name: asc.StableID(), Arguments: args("getclass", apk, "Lexample/Test;")}}},
		{Content: "complete"},
	}}
	a, _ := newTestAgent(t, p)
	if err := a.AddLocalTools([]localtool.Manifest{asc}); err != nil {
		t.Fatal(err)
	}
	if err := a.ConfigureSkills([]string{filepath.Join("..", "..", ".trace", "skills", "asc")}); err != nil {
		t.Fatal(err)
	}
	s, err := a.Run(context.Background(), createTestRun(t, a))
	if err != nil || s.Run.Status != StatusCompleted || len(s.Actions) != 6 {
		t.Fatalf("ASC chain: status=%s actions=%d err=%v", s.Run.Status, len(s.Actions), err)
	}
	for i, expected := range []string{asc.StableID(), asc.StableID(), "getmanifest", "Lexample/Test;", "first", "class Test"} {
		if s.Actions[i].Result.ExitCode != 0 || !strings.Contains(s.Actions[i].Result.Stdout, expected) {
			t.Fatalf("action %s: %+v", s.Actions[i].CallID, s.Actions[i].Result)
		}
	}
	for _, action := range s.Actions[3:] {
		if action.Adapter != "local" || action.LocalName != "droidasc" || action.Result.EvidenceID == "" || action.Result.WorkerPID == 0 {
			t.Fatalf("missing execution evidence: %+v", action)
		}
	}
	result, err := asc.Execute(context.Background(), "asc-error", "missing", json.RawMessage(args("listclass", apk+".absent")))
	if err == nil || result.ExitCode == nil || *result.ExitCode == 0 || result.OutcomeUncertain {
		t.Fatalf("missing APK was not a definite failure: %+v %v", result, err)
	}
	if _, _, err = asc.Invocation(json.RawMessage(`{"argv":"listclass"}`)); err == nil {
		t.Fatal("non-array argv accepted")
	}
}
